long wia_ref_hashdata(const unsigned char* pbData, unsigned long cbData,
                      unsigned char* pbHash, unsigned long cbHash)
{
    unsigned long i, j;

    if (pbData == 0 || pbHash == 0) return (long)0x80070057;   /* E_INVALIDARG */

    for (j = 0; j < cbHash; ++j) pbHash[j] = (unsigned char)j;  /* the seed, and it wraps */

    for (i = cbData; i-- > 0; )                                 /* LAST source byte first */
        for (j = cbHash; j-- > 0; )                             /* HIGHEST digest byte first, and
                                                                   pbData[i] RE-READ inside this
                                                                   loop -- both of which are
                                                                   unobservable while the buffers
                                                                   are disjoint and decide the
                                                                   answer when they overlap */
            pbHash[j] = REF_T[pbHash[j] ^ pbData[i]];

    return 0;                                                   /* S_OK */
}
